//! Trace-driven, instantaneous worker capacity changes for offline replay.
//! Logical worker IDs are monotonic; later Add events allocate fresh IDs.

use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "action", rename_all = "snake_case")]
pub enum WorkerAvailabilityAction {
    Add { count: usize },
    Reclaim { worker_ids: Vec<usize> },
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct WorkerAvailabilityEvent {
    pub time_ms: f64,
    #[serde(flatten)]
    pub change: WorkerAvailabilityAction,
}

/// A full restart discards any output generated by the lost execution and
/// resubmits the original prompt and output budget through placement.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum WorkerRecoveryMode {
    #[default]
    None,
    Restart,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct WorkerRecoveryPolicy {
    pub mode: WorkerRecoveryMode,
    /// Maximum number of restarts for one logical request.
    pub max_restarts: usize,
}

impl Default for WorkerRecoveryPolicy {
    fn default() -> Self {
        Self { mode: WorkerRecoveryMode::None, max_restarts: 0 }
    }
}

/// Research-specific counters. Successful logical requests remain counted only
/// once in ReplayReport.request_counts; these measure discarded attempts.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize)]
pub struct WorkerAvailabilityStats {
    pub added_workers: usize,
    pub reclaimed_workers: usize,
    pub reclaim_events: usize,
    pub interrupted_attempts: usize,
    pub restarted_attempts: usize,
    pub permanently_failed_requests: usize,
}

pub(crate) fn validate_events(events: &[WorkerAvailabilityEvent]) -> anyhow::Result<()> {
    let mut previous = 0.0;
    for (index, event) in events.iter().enumerate() {
        anyhow::ensure!(
            event.time_ms.is_finite() && event.time_ms >= previous,
            "worker availability events must have finite, nonnegative, nondecreasing timestamps (event {index})"
        );
        match &event.change {
            WorkerAvailabilityAction::Add { count } =>
                anyhow::ensure!(*count > 0, "add event must specify a positive worker count"),
            WorkerAvailabilityAction::Reclaim { worker_ids } => {
                anyhow::ensure!(!worker_ids.is_empty(), "reclaim event must specify worker IDs");
                let unique = worker_ids.iter().copied().collect::<std::collections::BTreeSet<_>>();
                anyhow::ensure!(unique.len() == worker_ids.len(), "reclaim event repeats worker IDs");
            }
        }
        previous = event.time_ms;
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn serializes_reclaim_event() {
        let event: WorkerAvailabilityEvent = serde_json::from_str(
            r#"{"time_ms":100.0,"action":"reclaim","worker_ids":[4,5,6,7]}"#,
        ).unwrap();
        assert_eq!(
            event.change,
            WorkerAvailabilityAction::Reclaim { worker_ids: vec![4, 5, 6, 7] }
        );
        validate_events(&[event]).unwrap();
    }

    #[test]
    fn rejects_unsorted_events() {
        let events = vec![
            WorkerAvailabilityEvent { time_ms: 5.0, change: WorkerAvailabilityAction::Add { count: 4 } },
            WorkerAvailabilityEvent { time_ms: 4.0, change: WorkerAvailabilityAction::Add { count: 4 } },
        ];
        assert!(validate_events(&events).is_err());
    }
}
